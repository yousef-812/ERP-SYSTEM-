import { jsPDF } from "jspdf";
import "jspdf-autotable";

export const generateDeliveryNotePDF = (order, settings) => {
  const doc = new jsPDF();
  const isRtl = false; // Simplified for now, can add RTL support if needed

  // Header
  doc.setFontSize(22);
  doc.setTextColor(40, 44, 52);
  doc.text(settings.CompanyName || "ERP SYSTEM", 14, 20);
  
  doc.setFontSize(10);
  doc.setTextColor(100);
  doc.text(settings.Address || "", 14, 28);
  
  doc.setFontSize(18);
  doc.setTextColor(0);
  doc.text("DELIVERY NOTE", 140, 20);
  
  doc.setFontSize(10);
  doc.text(`Date: ${new Date(order.orderDate).toLocaleDateString()}`, 140, 28);
  doc.text(`Order #: ${order.id.substring(0, 8).toUpperCase()}`, 140, 34);

  doc.setDrawColor(200);
  doc.line(14, 40, 196, 40);

  // Billing & Shipping Info
  doc.setFontSize(12);
  doc.setFont("helvetica", "bold");
  doc.text("Ship To:", 14, 50);
  doc.setFont("helvetica", "normal");
  doc.text(order.customer?.name || "Generic Customer", 14, 57);
  doc.text(order.customer?.address || "", 14, 64);
  doc.text(order.customer?.phone || "", 14, 71);

  // Items Table
  const tableData = order.details.map(item => [
    item.product?.name || "Product",
    item.quantity,
    "________" // Placeholder for recipient signature/ticks
  ]);

  doc.autoTable({
    startY: 85,
    head: [['Product Description', 'Quantity', 'Received']],
    body: tableData,
    theme: 'striped',
    headStyles: { fillColor: [41, 128, 185], textColor: 255 },
    styles: { fontSize: 10, cellPadding: 5 }
  });

  // Footer / Signature
  const finalY = doc.lastAutoTable.finalY + 30;
  doc.text("Delivered By: ____________________", 14, finalY);
  doc.text("Recipient Signature: ____________________", 110, finalY);
  
  doc.setFontSize(8);
  doc.setTextColor(150);
  doc.text("Generated by ERP Suite Professional", 105, 285, { align: 'center' });

  doc.save(`DeliveryNote_${order.id.substring(0, 8)}.pdf`);
};
